    log_event("user_message", query=query, method="run")
    try:
        response = _original_run(self, query, top_k=top_k)
        log_event(
            "final_response",
            query=query,
            answer_type=response.answer_type,
            handoff=response.requires_handoff,
            citations=[c.source_file for c in (response.citations or [])],
        )
        return response
    except Exception as exc:
        log_event(
            "agent_error",
            query=query,
            error_type=type(exc).__name__,
            error=str(exc),
        )
        raise


