    def _answer_shipping_address(
        self,
        evidence: EvidenceResult,
    ) -> AgentResponse | None:

        address_chunk = None

        for result in evidence.chunks:

            chunk = result.chunk

            source = (
                chunk.source_file or ""
            ).lower()

            heading = (
                chunk.heading or ""
            ).lower()

            content = (
                chunk.content or ""
            ).lower()

            # --------------------------------------------------
            # Exact address-change policy is preferred.
            # --------------------------------------------------

            if (
                "order-changes-and-cancellations.md"
                in source
                and "address" in heading
            ):
                address_chunk = result
                break

            if (
                "address changes" in heading
                or "shipping address" in content
            ):

                if address_chunk is None:
                    address_chunk = result

        if address_chunk is None:
            return None

        citations = CitationBuilder.build_many(
            [address_chunk]
        )

        message = (
            "You can request a change to your shipping "
            "address within **30 minutes** while an order "
            "is still pending. Once the order enters "
            "processing, Aster & Row cannot guarantee the "
            "change. After shipment, address modifications "
            "must be handled through the carrier."
        )

        return AgentResponse(
            answer_type="grounded",
            message=message,
            citations=citations,
            evidence=evidence,
        )

