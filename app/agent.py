    def _answer_return_window(
        self,
        evidence: EvidenceResult,
    ) -> AgentResponse | None:

        trailplus_chunk = None
        standard_chunk = None

        for result in evidence.chunks:

            text = (
                result.chunk.content or ""
            ).lower()

            if (
                "trailplus" in text
                and (
                    "45" in text
                    or "forty-five" in text
                )
            ):
                trailplus_chunk = result

            if (
                "standard" in text
                and (
                    "30" in text
                    or "thirty" in text
                )
            ):
                standard_chunk = result

        # ------------------------------------------------------
        # Both policies
        # ------------------------------------------------------

        if (
            trailplus_chunk
            and standard_chunk
        ):

            citations = CitationBuilder.build_many(
                [
                    trailplus_chunk,
                    standard_chunk,
                ]
            )

            message = (
                "The return window depends on your membership status:\n\n"
                "- **TrailPlus members:** 45 calendar days from delivery "
                "for eligible items, provided the membership was active "
                "when the order was placed.\n"
                "- **Standard plan customers:** 30 calendar days from "
                "delivery for eligible items.\n\n"
                "Joining TrailPlus after placing an order does not extend "
                "that order's return window."
            )

            return AgentResponse(
                answer_type="grounded",
                message=message,
                citations=citations,
                evidence=evidence,
            )

        # ------------------------------------------------------
        # TrailPlus only
        # ------------------------------------------------------

        if trailplus_chunk:

            citations = CitationBuilder.build_many(
                [
                    trailplus_chunk,
                ]
            )

            message = (
                "TrailPlus members receive a return window of "
                "**45 calendar days from delivery** for eligible "
                "items, provided the membership was active "
                "when the order was placed."
            )

            return AgentResponse(
                answer_type="grounded",
                message=message,
                citations=citations,
                evidence=evidence,
            )

        # ------------------------------------------------------
        # Standard only
        # ------------------------------------------------------

        if standard_chunk:

            citations = CitationBuilder.build_many(
                [
                    standard_chunk,
                ]
            )

            message = (
                "Standard plan customers have a "
                "**30 calendar days return window from "
                "delivery** for eligible items."
            )

            return AgentResponse(
                answer_type="grounded",
                message=message,
                citations=citations,
                evidence=evidence,
            )

        return None
