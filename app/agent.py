    # ==========================================================
    # ORDER LOOKUP
    # ==========================================================

    def _run_order_lookup(
        self,
        query: str,
    ) -> AgentResponse:

        order_id = self._extract_order_id(
            query
        )

        # ------------------------------------------------------
        # Missing order ID
        # ------------------------------------------------------

        if order_id is None:

            return AgentResponse(
                answer_type="clarification",
                message=(
                    "An order ID is required to look up "
                    "order information. Please provide "
                    "your order ID, for example ORD-1007."
                ),
                citations=[],
                evidence=None,
            )

        # ------------------------------------------------------
        # Deterministic order lookup
        # ------------------------------------------------------

        result = self.order_lookup_service.lookup(
            order_id
        )

        # ------------------------------------------------------
        # Unknown order
        # ------------------------------------------------------

                # ------------------------------------------------------
        # Unknown order
        # ------------------------------------------------------

        if not result.found:

            return AgentResponse(
                answer_type="order_not_found",
                message=(
                    f"No order was found for {order_id}. "
                    "Please check the order ID or contact support "
                    "for assistance."
                ),
                citations=[],
                evidence=None,
            )

        # ------------------------------------------------------
        # Customer-safe response
        # ------------------------------------------------------

        parts = []

        status = (
            result.status or ""
        ).strip().lower()

        if status:

            parts.append(
                f"The status of {result.order_id} is "
                f"**{status}**."
            )

        # Customer-safe message supplied by lookup service.

        if result.customer_safe_message:

            parts.append(
                result.customer_safe_message
            )

        # ------------------------------------------------------
        # Carrier
        # ------------------------------------------------------

        if result.carrier:

            parts.append(
                f"Carrier: **{result.carrier}**."
            )

        # ------------------------------------------------------
        # Tracking number
        # ------------------------------------------------------

        if result.tracking_number:

            parts.append(
                "Tracking number: "
                f"**{result.tracking_number}**."
            )

        # ------------------------------------------------------
        # Estimated delivery
        # ------------------------------------------------------

        if result.estimated_delivery:

            parts.append(
                "Estimated delivery: "
                f"**{result.estimated_delivery}**."
            )

        message = " ".join(parts).strip()

        if not message:

            message = (
                f"Order {result.order_id} was found, "
                "but there is no customer-safe status "
                "information available."
            )

        return AgentResponse(
            answer_type="order_lookup",
            message=message,
            citations=[],
            evidence=None,
        )

