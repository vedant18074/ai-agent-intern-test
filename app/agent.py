    # GENERIC GROUNDED RESPONSE
    # ==========================================================

    def _generic_grounded_response(
        self,
        evidence: EvidenceResult,
    ) -> AgentResponse:

        citations = CitationBuilder.build_many(
            evidence.chunks
        )

        if not evidence.chunks:

            return AgentResponse(
                answer_type="insufficient_evidence",
                message=(
                    "I don't have enough information in the "
                    "knowledge base to answer this reliably."
                ),
                citations=[],
                evidence=evidence,
            )

        # Use the strongest retrieved passage to provide a
        # grounded fallback answer.

        best = evidence.chunks[0].chunk

        message = (
            best.content or ""
        ).strip()

        if not message:

            return AgentResponse(
                answer_type="insufficient_evidence",
                message=(
                    "I don't have enough information in the "
                    "knowledge base to answer this reliably."
                ),
                citations=[],
                evidence=evidence,
            )

        return AgentResponse(
            answer_type="grounded",
            message=message,
            citations=citations,
            evidence=evidence,
        )

    
    # ==========================================================
    # RETRIEVE + ANALYZE EVIDENCE
    # ==========================================================

    def _retrieve_evidence(
        self,
        query: str,
        top_k: int,
    ) -> EvidenceResult:

        retrieved = (
            self.retrieval_service.retrieve(
                query,
                top_k=top_k,
            )
        )

        log_event(
            "retrieval",
            query=query,
            top_k=top_k,
            retrieved_count=len(retrieved),
            retrieved=[
                {
                    "source_file": r.chunk.source_file,
                    "heading": r.chunk.heading,
                    "score": r.score,
                    "status": r.chunk.status,
                    "authority": r.chunk.policy_authority,
                }
                for r in retrieved
            ],
        )

        evidence = (
            self.evidence_analyzer.analyze(
                retrieved
            )
        )

        evidence = self._select_best_evidence(
            evidence
        )

        log_event(
            "evidence",
            query=query,
            selected_count=len(evidence.chunks),
            conflict=evidence.has_conflict,
            excluded_count=len(evidence.excluded_chunks),
            selected_sources=[
                r.chunk.source_file
                for r in evidence.chunks
            ],
        )

        return evidence

    # ==========================================================
    # DETERMINISTIC KNOWLEDGE-BASE ANSWERS
    # ==========================================================

    def _answer_shipping_country(
        self,
        query: str,
        evidence: EvidenceResult,
    ) -> AgentResponse | None:
        """
        Answer international shipping questions directly from
        retrieved evidence.

        This prevents generic LLM fallbacks such as:
        'Relevant evidence was found.'
        """

        text = query.lower()

        # Only handle international shipping questions here.
        shipping_terms = [
            "ship internationally",
            "international shipping",
            "ship to",
            "shipping to",
            "deliver to",
            "delivery to",
            "canada",
            "germany",
        ]

        if not any(term in text for term in shipping_terms):
            return None

        relevant = []

        for result in evidence.chunks:

            chunk_text = (
                result.chunk.content or ""
            ).lower()

            source = (
                result.chunk.source_file or ""
            ).lower()

            if (
                "06-international-shipping.md" in source
                or "international" in chunk_text
            ):
                relevant.append(result)

        if not relevant:
            return None

        # ------------------------------------------------------
        # Canada
        # ------------------------------------------------------

        if "canada" in text:

            canada_supported = any(
                "canada" in (
                    result.chunk.content or ""
                ).lower()
                for result in relevant
            )

            if canada_supported:

                citations = CitationBuilder.build_many(
                    relevant[:2]
                )

                message = (
                    "Yes. **Canada is supported** for "
                    "international shipping. Delivery typically "
                    "takes **5–9 business days after dispatch**, "
                    "and **duties or taxes are not prepaid**."
                )

                return AgentResponse(
                    answer_type="grounded",
                    message=message,
                    citations=citations,
                    evidence=evidence,
                )

        # ------------------------------------------------------
        # Germany / unsupported country
        # ------------------------------------------------------

        if "germany" in text:

            citations = CitationBuilder.build_many(
                relevant[:2]
            )

            message = (
                "Shipping to Germany is not currently available "
                "according to the international shipping policy. "
                "shipping policy."
            )

            return AgentResponse(
                answer_type="grounded",
                message=message,
                citations=citations,
                evidence=evidence,
            )

        return None


