    @staticmethod
    def _is_active_official(
        result,
    ) -> bool:

        chunk = result.chunk

        status = (
            chunk.status or ""
        ).strip().lower()

        authority = (
            chunk.policy_authority or ""
        ).strip().lower()

        return (
            status == "active"
            and authority == "official"
        )

    @staticmethod
    def _is_active(
        result,
    ) -> bool:

        status = (
            result.chunk.status or ""
        ).strip().lower()

        return status == "active"

    def _select_best_evidence(
        self,
        evidence: EvidenceResult,
    ) -> EvidenceResult:

        chunks = evidence.chunks

        if not chunks:
            return evidence

        # ------------------------------------------------------
        # First preference:
        #
        # active + official
        # ------------------------------------------------------

        active_official = [
            result
            for result in chunks
            if self._is_active_official(result)
        ]

        if active_official:

            selected = active_official

        else:

            # --------------------------------------------------
            # Second preference:
            #
            # active sources
            # --------------------------------------------------

            active = [
                result
                for result in chunks
                if self._is_active(result)
            ]

            if active:
                selected = active
            else:
                selected = chunks

        # ------------------------------------------------------
        # Remove duplicate source/headings.
        #
        # Keep highest-scoring result.
        # ------------------------------------------------------

        unique = {}

        for result in selected:

            chunk = result.chunk

            key = (
                chunk.source_file,
                chunk.heading,
            )

            previous = unique.get(key)

            if (
                previous is None
                or result.score > previous.score
            ):
                unique[key] = result

        selected = list(
            unique.values()
        )

        # Highest relevance first.

        selected.sort(
            key=lambda item: item.score,
            reverse=True,
        )

        return EvidenceResult(
            chunks=selected,
            conflicts=evidence.conflicts,
            excluded_chunks=evidence.excluded_chunks,
        )

