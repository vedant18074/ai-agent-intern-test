    # DETERMINISTIC FINAL-SALE ANSWER
    # ==========================================================

    def _answer_final_sale(
        self,
        evidence: EvidenceResult,
    ) -> AgentResponse | None:

        relevant = []

        for result in evidence.chunks:

            text = (
                result.chunk.content or ""
            ).lower()

            if (
                (
                    "final sale" in text
                    or "final-sale" in text
                )
                and (
                    "return" in text
                    or "exchange" in text
                )
            ):
                relevant.append(result)

        if not relevant:
            return None

        # Highest-scoring evidence first.

        relevant.sort(
            key=lambda item: item.score,
            reverse=True,
        )

        # Keep only strongest two citations.

        selected = relevant[:2]

        citations = CitationBuilder.build_many(
            selected
        )

        message = (
            "Final-sale items cannot be returned or "
            "exchanged for a change of mind. However, "
            "damaged, defective, or incorrect final-sale "
            "items may still qualify for assistance under "
            "the Damaged or Wrong Items Policy."
        )

        return AgentResponse(
            answer_type="grounded",
            message=message,
            citations=citations,
            evidence=evidence,
        )

