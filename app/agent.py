    # ============================================================
    # PRIVATE / INTERNAL INFORMATION DETECTION
    # ============================================================

    @staticmethod
    def _is_private_order_information_question(
        query: str,
    ) -> bool:
        """
        Detect requests for sensitive/private order information.

        Legitimate order-management questions such as:
            "Can I change my shipping address?"
            "Can I update my delivery address?"

        must NOT be blocked.
        """

        text = query.lower().strip()

        # --------------------------------------------------------
        # Internal risk information
        # --------------------------------------------------------

        risk_terms = [
            "risk score",
            "internal risk",
            "risk rating",
            "fraud score",
            "fraud risk",
            "internal score",
        ]

        if any(term in text for term in risk_terms):
            return True

        # --------------------------------------------------------
        # Internal/private notes
        # --------------------------------------------------------

        internal_terms = [
            "internal note",
            "internal notes",
            "internal comment",
            "internal comments",
            "staff note",
            "staff notes",
            "agent note",
            "agent notes",
            "internal information",
        ]

        if any(term in text for term in internal_terms):
            return True

        # --------------------------------------------------------
        # Customer email
        # --------------------------------------------------------

        email_terms = [
            "email address",
            "customer email",
            "email for",
            "email on the order",
        ]

        if any(term in text for term in email_terms):
            return True

        # --------------------------------------------------------
        # Shipping / delivery / billing address
        # --------------------------------------------------------

        address_terms = [
            "shipping address",
            "delivery address",
            "billing address",
        ]

        # These indicate that the customer wants to MODIFY
        # an address rather than reveal it.
        address_change_terms = [
            "change",
            "update",
            "modify",
            "correct",
            "edit",
        ]

        asks_for_address = any(
            term in text
            for term in address_terms
        )

        asks_to_change_address = any(
            term in text
            for term in address_change_terms
        )

        # Example:
        # "Can I change my shipping address?"
        # -> NOT private information
        if asks_for_address and not asks_to_change_address:

            address_request_terms = [
                "what is",
                "what's",
                "tell me",
                "show me",
                "give me",
                "provide",
                "where is",
                "where's",
            ]

            if any(
                term in text
                for term in address_request_terms
            ):
                return True

        return False
