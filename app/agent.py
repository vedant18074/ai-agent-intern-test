class SupportAgent:
    """
    Reliable Aster & Row customer support agent.

    Processing order:

    1. Detect explicit order IDs.
    2. Protect private/internal order information.
    3. Perform deterministic order lookup.
    4. Detect generic order questions.
    5. Retrieve knowledge-base evidence.
    6. Prioritize active/official evidence.
    7. Detect conflicts.
    8. Handle deterministic policy questions.
    9. Use LLM only when appropriate.
    10. Never allow the LLM to generate order information.

    Important safety properties:

    - Order information is NEVER generated by the LLM.
    - Internal/private order information is never exposed.
    - Time-specific return questions are not answered from
      unrelated evidence.
    - Shipping-address changes are NOT treated as private
      information requests.
    """

    ORDER_ID_PATTERN = re.compile(
        r"\bORD-\d+\b",
        re.IGNORECASE,
    )

    # ==========================================================
    # INITIALIZATION
    # ==========================================================

    def __init__(
        self,
        retrieval_service: RetrievalService,
        evidence_analyzer: EvidenceAnalyzer,
        llm_service: LLMService | None = None,
        order_lookup_service: OrderLookupService | None = None,
    ):
        self.retrieval_service = retrieval_service
        self.evidence_analyzer = evidence_analyzer

        self.llm_service = (
            llm_service
            or LLMService()
        )

        self.order_lookup_service = (
            order_lookup_service
            or OrderLookupService()
        )

    # ==========================================================
    # ORDER ID DETECTION
    # ==========================================================

    @classmethod
    def _extract_order_id(
        cls,
        query: str,
    ) -> str | None:

        match = cls.ORDER_ID_PATTERN.search(
            query
        )

        if not match:
            return None

        return match.group(0)

    @staticmethod
    def _is_order_question(
        query: str,
    ) -> bool:

        return (
            SupportAgent._extract_order_id(
                query
            )
            is not None
        )

