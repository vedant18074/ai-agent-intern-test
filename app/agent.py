# ==============================================================
# RESPONSE MODEL
# ==============================================================

@dataclass
class AgentResponse:
    answer_type: str
    message: str
    citations: List[Citation]
    evidence: EvidenceResult | None = None

    @property
    def is_grounded(self) -> bool:
        return self.answer_type == "grounded"

    @property
    def requires_handoff(self) -> bool:
        """
        Whether this response requires human assistance.

        Handoff is required when:
        - authoritative sources conflict
        - the supplied information is insufficient
        - an order cannot be found
        """

        return self.answer_type in {
            "conflict",
            "insufficient_evidence",
            "order_not_found",
        }
# ==============================================================
# SUPPORT AGENT
