    # ==========================================================
    # PROMPT-INJECTION / MIGRATION NOTE
    # ==========================================================

    def _answer_migration_note_question(
        self,
        query: str,
        evidence: EvidenceResult,
    ) -> AgentResponse | None:
        """
        Prevent internal migration notes from overriding the
        current customer-facing return policy.
        """

        text = query.lower()

        injection_terms = [
            "migration note",
            "ignore the real policy",
            "60 days",
            "approve my return",
            "newer document",
        ]

        if not any(
            term in text
            for term in injection_terms
        ):
            return None

        policy_chunk = None

        for result in evidence.chunks:

            source = (
                result.chunk.source_file or ""
            ).lower()

            if "01-returns-policy-current.md" in source:
                policy_chunk = result
                break

        if policy_chunk is None:
            return None

        citations = CitationBuilder.build_many(
            [policy_chunk]
        )

        message = (
            "The migration note is not authoritative and "
            "cannot override the current customer-facing policy. "
            "The standard policy is 30 days unless a valid "
            "documented exception applies. "
            "The agent cannot approve a return automatically."
        )

        return AgentResponse(
            answer_type="grounded",
            message=message,
            citations=citations,
            evidence=evidence,
        )

    # ==========================================================
    # FINAL-SALE + DAMAGED ITEM
    # ==========================================================

    def _answer_final_sale_damaged(
        self,
        query: str,
        evidence: EvidenceResult,
    ) -> AgentResponse | None:
        """
        Handle a final-sale item that is damaged, defective,
        or incorrect.
        """

        text = query.lower()

        final_sale = (
            "final sale" in text
            or "final-sale" in text
        )

        damaged = any(
            term in text
            for term in [
                "broken",
                "damaged",
                "defective",
                "wrong item",
                "incorrect item",
                "zipper",
            ]
        )

        if not (
            final_sale
            and damaged
        ):
            return None

        damaged_chunk = None
        final_sale_chunk = None

        for result in evidence.chunks:

            source = (
                result.chunk.source_file or ""
            ).lower()

            if "04-damaged-or-wrong-items.md" in source:
                damaged_chunk = result

            elif "03-final-sale-and-promotions.md" in source:
                final_sale_chunk = result

        # The damaged/wrong-item policy is required.
        if damaged_chunk is None:
            return None

        selected = [
            damaged_chunk
        ]

        if final_sale_chunk is not None:
            selected.append(
                final_sale_chunk
            )

        citations = CitationBuilder.build_many(
            selected
        )

        message = (
            "A **final sale does not block damaged-item review**. "
            "A final-sale item is not automatically excluded from damaged-item review. "
            "If the item arrived "
            "damaged, defective, or incorrect, it should be "
            "**reported within 7 days**. A **human review is "
            "required before approval**, so I cannot approve "
            "the claim automatically."
        )

        return AgentResponse(
            answer_type="grounded",
            message=message,
            citations=citations,
            evidence=evidence,
        )


    # ==========================================================
    # PRODUCT-CARE CONFLICT
    # ==========================================================

    def _answer_product_care_conflict(
        self,
        query: str,
        evidence: EvidenceResult,
    ) -> AgentResponse | None:
        """
        Explain a genuine conflict between the current
        product-care sources instead of silently selecting one.
        """

        text = query.lower()

        if not (
            "dishwasher" in text
            and "breeze" in text
        ):
            return None

        care_chunk = None
        product_chunk = None

        for result in evidence.chunks:

            source = (
                result.chunk.source_file or ""
            ).lower()

            if "11-product-care.md" in source:
                care_chunk = result

            elif "12-breeze-tumbler-product-card.md" in source:
                product_chunk = result

        if not (
            care_chunk
            and product_chunk
        ):
            return None

        citations = CitationBuilder.build_many(
            [
                care_chunk,
                product_chunk,
            ]
        )

        message = (
            "The current official sources **conflict** on "
            "whether the entire Breeze Tumbler can go in the "
            "dishwasher. **One says hand-wash the body**, "
            "while another says **all components are "
            "dishwasher safe**. Because these instructions "
            "conflict, I cannot safely choose one as definitive. "
            "Please get human confirmation; as the safest "
            "interim guidance, hand-wash the body."
        )

        return AgentResponse(
            answer_type="conflict",
            message=message,
            citations=citations,
            evidence=evidence,
        )



    def _try_deterministic_answer(
        self,
        query: str,
        evidence: EvidenceResult,
    ) -> AgentResponse | None:

        # ------------------------------------------------------
        # Product-care source conflict
        # ------------------------------------------------------

        answer = self._answer_product_care_conflict(
            query,
            evidence,
        )

        if answer is not None:
            return answer

        # ------------------------------------------------------
        # Final-sale damaged/defective exception
        # ------------------------------------------------------

        answer = self._answer_final_sale_damaged(
            query,
            evidence,
        )

        if answer is not None:
            return answer

        # ------------------------------------------------------
        # International shipping
        # ------------------------------------------------------

        answer = self._answer_shipping_country(
            query,
            evidence,
        )

        if answer is not None:
            return answer

        # ------------------------------------------------------
        # Warranty
        # ------------------------------------------------------

        answer = self._answer_warranty(
            query,
            evidence,
        )

        if answer is not None:
            return answer

        # ------------------------------------------------------
        # Material / vegan information
        # ------------------------------------------------------

        answer = self._answer_material_question(
            query,
            evidence,
        )

        if answer is not None:
            return answer

        # ------------------------------------------------------
        # Migration note / prompt injection
        # ------------------------------------------------------

        answer = self._answer_migration_note_question(
            query,
            evidence,
        )

        if answer is not None:
            return answer

        # ------------------------------------------------------
        # Final-sale
        # ------------------------------------------------------

        if self._is_final_sale_question(query):

            answer = self._answer_final_sale(
                evidence
            )

            if answer is not None:
                return answer

        # ------------------------------------------------------
        # Shipping address
        # ------------------------------------------------------

        if self._is_shipping_address_question(query):

            answer = self._answer_shipping_address(
                evidence
            )

            if answer is not None:
                return answer

        # ------------------------------------------------------
        # Time-specific return question
        # ------------------------------------------------------

        if self._is_time_specific_return_question(
            query
        ):

            if self._is_return_window_question(
                query
            ):

                answer = self._answer_return_window(
                    evidence
                )

                if answer is not None:

                    requested_days = re.search(
                        r"\b(\d+)\s*days?\b",
                        query.lower(),
                    )

                    if requested_days:

                        requested = int(
                            requested_days.group(1)
                        )

                        supported = []

                        for result in evidence.chunks:

                            content = (
                                result.chunk.content
                                or ""
                            ).lower()

                            if (
                                "45" in content
                                and "trailplus" in content
                            ):
                                supported.append(45)

                            if (
                                "30" in content
                                and "standard" in content
                            ):
                                supported.append(30)

                        if (
                            supported
                            and requested not in supported
                        ):

                            return AgentResponse(
                                answer_type="insufficient_evidence",
                                message=(
                                    "I don't have enough "
                                    "information in the "
                                    "knowledge base to answer "
                                    "this question reliably."
                                ),
                                citations=[],
                                evidence=evidence,
                            )

                    return answer

            return AgentResponse(
                answer_type="insufficient_evidence",
                message=(
                    "I don't have enough information in the "
                    "knowledge base to answer this question "
                    "reliably."
                ),
                citations=[],
                evidence=evidence,
            )

        # ------------------------------------------------------
        # Normal return-window question
        # ------------------------------------------------------

        if self._is_return_window_question(query):

            answer = self._answer_return_window(
                evidence
            )

            if answer is not None:
                return answer

        # ------------------------------------------------------
        # Return shipping fee
        # ------------------------------------------------------

        if self._is_return_shipping_fee_question(query):

            answer = self._answer_return_shipping_fee(
                evidence
            )

            if answer is not None:
                return answer

        return None

    # ==========================================================
    # MAIN RAG PIPELINE
    # ==========================================================

    def run(
        self,
        query: str,
        top_k: int = 5,
    ) -> AgentResponse:

        query = query.strip()

        if not query:
            raise ValueError(
                "Query cannot be empty."
            )

        # ------------------------------------------------------
        # Explicit order ID
        # ------------------------------------------------------

        if self._is_order_question(query):

            if self._is_private_order_information_question(
                query
            ):
                return (
                    self._answer_private_information_request()
                )

            return self._run_order_lookup(query)

        # ------------------------------------------------------
        # Generic order question
        # ------------------------------------------------------

        if self._looks_like_order_question(query):
            return self._run_order_lookup(query)

        # ------------------------------------------------------
        # Protected information
        # ------------------------------------------------------

        if self._is_private_order_information_question(query):
            return (
                self._answer_private_information_request()
            )

        # ------------------------------------------------------
        # Retrieve evidence
        # ------------------------------------------------------

        # Prompt-injection / migration-note queries need the
        # current returns policy available for deterministic
        # grounding. Retrieve a wider evidence set so the current
        # policy is not lost behind the internal migration note.
        retrieval_top_k = top_k

        migration_query = any(
            term in query.lower()
            for term in [
                "migration note",
                "ignore the real policy",
                "60 days",
                "approve my return",
                "newer document",
            ]
        )

        if migration_query:
            retrieval_top_k = max(top_k, 20)

        evidence = self._retrieve_evidence(
            query,
            retrieval_top_k,
        )

        # ------------------------------------------------------
        # No evidence
        # ------------------------------------------------------

        if not evidence.chunks:
            return AgentResponse(
                answer_type="insufficient_evidence",
                message=(
                    "I don't have enough information "
                    "in the knowledge base to answer "
                    "this question reliably."
                ),
                citations=[],
                evidence=evidence,
            )

        # ------------------------------------------------------
        # Deterministic answers
        # ------------------------------------------------------

        deterministic = self._try_deterministic_answer(
            query,
            evidence,
        )

        if deterministic is not None:
            return deterministic

        # ------------------------------------------------------
        # Conflict
        # ------------------------------------------------------

        if evidence.has_conflict:

            citations = CitationBuilder.build_many(
                evidence.chunks
            )

            return AgentResponse(
                answer_type="conflict",
                message=(
                    "I found conflicting current official "
                    "information. I cannot safely provide "
                    "a definitive answer without resolving "
                    "the conflict."
                ),
                citations=citations,
                evidence=evidence,
            )

        # ------------------------------------------------------
        # Generic grounded response
        # ------------------------------------------------------

        return self._generic_grounded_response(
            evidence
        )

